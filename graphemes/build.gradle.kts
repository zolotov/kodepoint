import me.zolotov.kodepoint.generator.UnicodeVersion
import me.zolotov.kodepoint.generator.graphemes.generateGraphemeData
import org.jetbrains.kotlin.gradle.tasks.KotlinCompilationTask

plugins {
    id("kodepoint.multiplatform")
}

// The Gradle path stays `:graphemes`; the published artifact is named after the library.
mavenPublishing {
    coordinates(artifactId = "kodepoint-graphemes")
}

val generateGraphemeData = tasks.register("generateGraphemeData") {
    description = "Generate the grapheme-cluster and emoji tables, the GraphemeBreakTest cases and the size report."
    val unicodeVersion = providers.gradleProperty("kodepoint.unicodeVersion")
    val cacheDir = layout.buildDirectory.dir("unicode-cache")
    val outputDir = layout.buildDirectory.dir("generated/sources/grapheme-data")
    val testOutputDir = layout.buildDirectory.dir("generated/sources/grapheme-test-data")
    val testResourcesDir = layout.buildDirectory.dir("generated/resources/grapheme-test-data")
    val metricsReport = layout.buildDirectory.file("reports/grapheme-data/metrics.json")
    inputs.property("unicodeVersion", unicodeVersion)
    outputs.dir(outputDir)
    outputs.dir(testOutputDir)
    outputs.dir(testResourcesDir)
    outputs.file(metricsReport)

    doLast {
        generateGraphemeData(
            UnicodeVersion(unicodeVersion.get()),
            outputDir = outputDir.get().asFile.toPath(),
            testOutputDir = testOutputDir.get().asFile.toPath(),
            testResourcesDir = testResourcesDir.get().asFile.toPath(),
            cacheDir = cacheDir.get().asFile.toPath(),
            additionalComment = "Generated by ./gradlew :graphemes:generateGraphemeData",
            metricsOutput = metricsReport.get().asFile.toPath(),
        )
    }
}

kotlin {
    sourceSets {
        commonMain {
            kotlin.srcDir(layout.buildDirectory.dir("generated/sources/grapheme-data"))
            dependencies {
                // Codepoint is part of this module's public API.
                api(project(":kodepoint"))
            }
        }
        commonTest {
            kotlin.srcDir(layout.buildDirectory.dir("generated/sources/grapheme-test-data"))
            dependencies {
                implementation(kotlin("test"))
            }
        }
        jvmTest {
            resources.srcDir(layout.buildDirectory.dir("generated/resources/grapheme-test-data"))
        }
    }
}

tasks.register("graphemeDataMetrics") {
    group = "reporting"
    description = "Generate the grapheme and emoji table size metrics as JSON."
    dependsOn(generateGraphemeData)
    val metricsReport = layout.buildDirectory.file("reports/grapheme-data/metrics.json")
    doLast {
        println("Grapheme data metrics report: ${metricsReport.get().asFile}")
    }
}

tasks.withType<KotlinCompilationTask<*>>().configureEach {
    dependsOn(generateGraphemeData)
}

tasks.matching {
    it.name.endsWith("sourcesjar", ignoreCase = true) || it.name.contains("dokka") ||
        it.name.endsWith("ProcessResources")
}.configureEach {
    dependsOn(generateGraphemeData)
}
